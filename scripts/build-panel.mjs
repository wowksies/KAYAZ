import path from 'node:path';
import JavaScriptObfuscator from 'javascript-obfuscator';

const root = process.cwd();
const sourcePath = path.join(root, 'scripts/panel/panel.src.js');
const outPath = path.join(root, 'assets/panel.js');

const source = fs.readFileSync(sourcePath, 'utf8');

const obfuscated = JavaScriptObfuscator.obfuscate(source, {
  target: 'browser',
  compact: true,
  simplify: true,
  identifierNamesGenerator: 'hexadecimal',
  renameGlobals: false,
  stringArray: true,
  stringArrayThreshold: 0.8,
  stringArrayEncoding: ['base64'],
  stringArrayRotate: true,
  stringArrayShuffle: true,
  stringArrayWrappersCount: 2,
  splitStrings: true,
  splitStringsChunkLength: 7,
  controlFlowFlattening: true,
  controlFlowFlatteningThreshold: 0.35,
  numbersToExpressions: true,
  transformObjectKeys: true,
  selfDefending: false,
  debugProtection: false,
  disableConsoleOutput: true,
  unicodeEscapeSequence: false
}).getObfuscatedCode();

fs.writeFileSync(
  outPath,
  '/* kayaz panel bundle. generated by scripts/build-panel.mjs - do not edit. */\n' + obfuscated + '\n'
);

const kb = (fs.statSync(outPath).size / 1024).toFixed(1);
console.log(`built ${path.relative(root, outPath)} (${kb} kb)`);
